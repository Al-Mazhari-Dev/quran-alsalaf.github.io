// تمييز مقررات الأسابيع بالتناوب (بطلب صاحب المشروع): مقرر يظهر في المصحف مظلَّلًا بدرجة خفيفة
// من «لون التطبيق»، والذي بعده بلا تظليل، وهكذا (٢٠٢٦-١١-١٤؛ كان قبلها بدرجتين خفيفتين متناوبتين،
// وقبلهما مقررًا ملوّنًا ثم عاديًّا)، فتتبيّن حدود المقررات بالنظر.
//
// المقررات في memos.json (weeks) مقاطع متصلة من الآيات بترتيب المصحف، فما كان ترتيبه زوجيًّا
// (الأول والثالث…) مظلَّل والفردي بلا تظليل. والتناوب بترتيب المصحف لا بترتيب المذكرة: فجزء عمّ
// المرتّب في مذكرته من آخره يتناوب كذلك، والأسبوع ذو المقطعين (التين والقدر، وبينهما العلق)
// يتناوب مقطعاه مع ما بينهما.
const cache = new WeakMap();

export function weekMap(quran) {
  let map = cache.get(quran);
  if (map) return map;

  const seg = new Int32Array(quran.verses.length).fill(-1);
  (quran.memos?.weeks ?? []).forEach(([from, to], i) => {
    for (let v = from; v <= to; v++) seg[v] = i;
  });
  // يُظلَّل من الصفحة كلمات الآيات وحدها — لا عنوان السورة ولا البسملة (بقرار صاحب المشروع).
  // وإظهار التظليل أو إخفاؤه بإعداد المستخدم (src/lib/settings.js)، لا هنا.
  // true لآية في مقرر مظلَّل، وfalse لآية في المقرر الذي بعده أو خارج المقررات
  const shaded = (v) => v >= 0 && seg[v] >= 0 && seg[v] % 2 === 0;

  map = { shaded };
  cache.set(quran, map);
  return map;
}
