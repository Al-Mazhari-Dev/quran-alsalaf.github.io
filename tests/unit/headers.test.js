// ترويسة الصفحة (السورة والجزء) كمصحف المدينة المطبوع — pageInfo في src/data/quran.js.
// الجدول أدناه منقول من صور صفحات المطبوع في مصحف جامعة الملك سعود (٢٠٢٦-١١-١٣)، لكل صفحة
// يبدأ فيها جزء أو سورة في وسطها؛ وبقية الصفحات فيها سورة واحدة وجزء واحد فلا تحتمل غيرهما.
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { pageInfo } from '../../src/data/quran.js';

const quran = JSON.parse(readFileSync('public/data/quran.json', 'utf8'));
const header = (p) => {
  const { suras, juz } = pageInfo(quran, p);
  return [suras.map((s) => s.n), juz];
};

// الصفحة: [السور المكتوبة في ترويسة المطبوع، الجزء]
const PRINTED = {
  62: [[3], 4], 106: [[5], 6], 121: [[5], 6], 201: [[9], 10], 221: [[11], 11], 235: [[11], 12],
  255: [[14], 13], 267: [[16], 14], 293: [[17], 15], 312: [[20], 16], 359: [[24], 18], 385: [[27], 20],
  396: [[28], 20], 404: [[29], 21], 434: [[34], 22], 440: [[36], 22], 458: [[39], 23], 467: [[40], 24],
  489: [[43], 25], 502: [[46], 26], 515: [[49], 26], 520: [[50], 26], 523: [[51], 27], 528: [[53], 27],
  531: [[55], 27], 534: [[56], 27], 537: [[56], 27], 545: [[59], 28], 551: [[61], 28], 554: [[63], 28],
  564: [[68], 29], 566: [[68], 29], 568: [[69], 29], 570: [[71], 29], 575: [[73], 29], 577: [[75], 29],
  578: [[75], 29], 580: [[77], 29], 583: [[78], 30], 586: [[81], 30], 587: [[82], 30], 589: [[84], 30],
  590: [[85], 30], 591: [[86, 87], 30], 592: [[88], 30], 593: [[89], 30], 594: [[90], 30],
  595: [[91, 92], 30], 596: [[93, 94], 30], 597: [[95, 96], 30], 598: [[97, 98], 30], 599: [[99, 100], 30],
  600: [[101, 102], 30], 601: [[103, 104, 105], 30], 602: [[106, 107, 108], 30],
  603: [[109, 110, 111], 30], 604: [[112, 113, 114], 30],
};

describe('ترويسة الصفحة كالمطبوع', () => {
  it('كل صفحة يبدأ فيها جزء أو سورة في وسطها: كما في صورتها من المطبوع', () => {
    for (const [p, printed] of Object.entries(PRINTED)) expect([Number(p), header(Number(p))]).toEqual([Number(p), printed]);
  });

  it('بقية الصفحات: سورتها الوحيدة وجزؤها الوحيد', () => {
    for (let p = 1; p <= 604; p++) {
      if (PRINTED[p]) continue;
      const suras = new Set();
      const juzs = new Set();
      for (const l of quran.pages[p - 1]) {
        if (l.h) suras.add(l.h);
        for (const [v] of l.g ?? []) {
          suras.add(quran.verses[v].s);
          juzs.add(quran.verses[v].j);
        }
      }
      expect([p, suras.size, juzs.size]).toEqual([p, 1, 1]);
      expect([p, header(p)]).toEqual([p, [[...suras], [...juzs][0]]]);
    }
  });

  it('القاعدة: عنوان السورة في السطر ٧ يُذكر، وفي السطر ٨ لا يُذكر', () => {
    // ٢٢١: عنوان هود في السطر ٧ · ٣٨٥: عنوان القصص في السطر ٨
    expect(quran.pages[220].findIndex((l) => l.h === 11)).toBe(6);
    expect(header(221)[0]).toEqual([11]);
    expect(quran.pages[384].findIndex((l) => l.h === 28)).toBe(7);
    expect(header(385)[0]).toEqual([27]);
  });

  it('السورة القصيرة يُذكر اسمها وإن بدأت في النصف الأسفل إن كان نصفها فأكثر في الصفحة', () => {
    // ٥٩١: الأعلى من السطر ١٠ (٦ أسطر من ١٠) · ٥٨٧: المطففين من السطر ١٢ (٤ أسطر من ٢١)، فلا تُذكر
    expect(header(591)[0]).toEqual([86, 87]);
    expect(header(587)[0]).toEqual([82]);
  });

  it('sura أول السور المذكورة، للتوافق', () => {
    expect(pageInfo(quran, 604).sura.n).toBe(112);
    expect(pageInfo(quran, 502).sura.n).toBe(46);
  });

  it('لا استثناءات يدوية في البيانات', () => {
    expect(quran.juzHeaders).toBeUndefined();
  });
});
